package cc.sirrus.ysmlib.cpm;

import java.util.*;

/**
 * Format independent CPM feature descriptions.  The values deliberately keep
 * their original {@link CpmValue} representation: both CPM formats allow
 * expressions in fields which must be evaluated per entity.
 */
public final class CpmFeatures {
    private CpmFeatures() {}

    public record Physics(String bone, List<CpmValue> parameters, CpmValue.ObjectValue source) {
        public Physics {
            Objects.requireNonNull(bone);
            parameters = List.copyOf(parameters);
            if (parameters.size() != 5) throw new IllegalArgumentException("CPM physics requires five parameters");
            Objects.requireNonNull(source);
        }
    }

    /** A source particle emitter.  Its fields remain available for expression evaluation. */
    public record Particle(String name, String parent, CpmValue.ObjectValue source) {
        public Particle {
            if (name == null || name.isBlank()) throw new IllegalArgumentException("CPM particle name is blank");
            if (parent == null || parent.isBlank()) parent = "none";
            Objects.requireNonNull(source);
        }
    }

    /** A source item attachment.  Rendering policy is selected by the host. */
    public record Item(String name, String parent, CpmValue.ObjectValue source) {
        public Item {
            if (name == null || name.isBlank()) throw new IllegalArgumentException("CPM item name is blank");
            if (parent == null || parent.isBlank()) parent = "none";
            Objects.requireNonNull(source);
        }
    }

    /** Runtime particle event generated by one entity tick. */
    public record Spawn(String name, String parent, double[] position, double[] velocity,
                        double speed, int lifetime, int count) {
        public Spawn {
            Objects.requireNonNull(name); Objects.requireNonNull(parent);
            position = vector(position, 0); velocity = vector(velocity, 0);
            if (!Double.isFinite(speed)) speed = 0;
            speed = Math.max(0, speed);
            lifetime = Math.max(1, lifetime); count = Math.max(1, count);
        }
        private static double[] vector(double[] value, double fallback) {
            var result = new double[]{fallback, fallback, fallback};
            if (value != null) for (int i = 0; i < Math.min(3, value.length); i++)
                if (Double.isFinite(value[i])) result[i] = value[i];
            return result;
        }
    }

    /** Returns all legacy and remake physics entries in source order. */
    public static List<Physics> physics(CpmDocument document) {
        Objects.requireNonNull(document);
        var result = new ArrayList<Physics>();
        if (document instanceof CpmDocument.Legacy legacy) {
            for (var bone : legacy.bones()) {
                var value = bone.source().fields().get("physics");
                if (value instanceof CpmValue.ArrayValue array && array.values().size() == 5)
                    result.add(new Physics(bone.id(), array.values(), bone.source()));
            }
        } else if (document instanceof CpmDocument.Remake remake) {
            // animation.js physicalize() calls are captured by the Java pose
            // runtime.  The JSON format itself has no per-bone physics array.
        }
        return List.copyOf(result);
    }

    public static List<Particle> particles(CpmDocument document) {
        Objects.requireNonNull(document);
        var result = new ArrayList<Particle>();
        if (document instanceof CpmDocument.Legacy legacy) {
            for (var bone : legacy.bones()) addParticles(result, bone.id(), bone.source().fields().get("particles"));
        } else if (document instanceof CpmDocument.Remake remake) {
            addParticles(result, "none", remake.source().fields().get("particles"));
            for (var part : remake.parts()) for (var model : part.geometry().models())
                for (var bone : model.bones()) addParticles(result, bone.name(), bone.source().fields().get("particles"));
        }
        return List.copyOf(result);
    }

    public static List<Item> items(CpmDocument document) {
        Objects.requireNonNull(document);
        var result = new ArrayList<Item>();
        if (document instanceof CpmDocument.Legacy legacy) {
            for (var bone : legacy.bones()) addItems(result, bone.id(), bone.source().fields().get("items"));
        } else if (document instanceof CpmDocument.Remake remake) {
            addItems(result, "none", remake.source().fields().get("items"));
            for (var part : remake.parts()) for (var model : part.geometry().models())
                for (var bone : model.bones()) addItems(result, bone.name(), bone.source().fields().get("items"));
        }
        return List.copyOf(result);
    }

    private static void addParticles(List<Particle> out, String defaultParent, CpmValue value) {
        if (value instanceof CpmValue.ArrayValue array) {
            int index = 0;
            for (var entry : array.values()) if (entry instanceof CpmValue.ObjectValue object) {
                String name = string(object, "name", "particle_" + index++);
                String parent = string(object, "parent", defaultParent);
                out.add(new Particle(name, parent, object));
            }
        } else if (value instanceof CpmValue.ObjectValue object) {
            for (var entry : object.fields().entrySet()) if (entry.getValue() instanceof CpmValue.ObjectValue definition) {
                out.add(new Particle(entry.getKey(), string(definition, "parent", defaultParent), definition));
            }
        }
    }

    private static void addItems(List<Item> out, String defaultParent, CpmValue value) {
        if (value instanceof CpmValue.ArrayValue array) {
            int index = 0;
            for (var entry : array.values()) if (entry instanceof CpmValue.ObjectValue object) {
                String name = string(object, "name", "item_" + index++);
                String parent = string(object, "parent", defaultParent);
                out.add(new Item(name, parent, object));
            }
        } else if (value instanceof CpmValue.ObjectValue object) {
            for (var entry : object.fields().entrySet()) if (entry.getValue() instanceof CpmValue.ObjectValue definition)
                out.add(new Item(entry.getKey(), string(definition, "parent", defaultParent), definition));
        }
    }

    private static String string(CpmValue.ObjectValue object, String key, String fallback) {
        var value = object.fields().get(key);
        return value instanceof CpmValue.StringValue text ? text.value() : fallback;
    }
}
